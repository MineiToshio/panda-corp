#!/bin/bash
# Declared outputs are normalized, empty fixture folders are harmless, every other input binds.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
FX=$(mktemp -d "${TMPDIR:-/tmp}/stamp-outputs.XXXXXX")
trap 'rm -rf "$FX"' EXIT
mkdir -p "$FX/.pandacorp" "$FX/e2e/fixtures/root" "$FX/bin" "$FX/src"
cp "$ROOT/plugin/templates/shared/.pandacorp/green-stamp.sh" "$FX/.pandacorp/"
cp "$ROOT/plugin/templates/stack-a-nextjs/verify.sh" "$FX/.pandacorp/verify.sh"
printf 'e2e/fixtures/root/ledger.json\ne2e/fixtures/root/ledger.json.lock/\ne2e/fixtures/root/Library/\ne2e/fixtures/root/output with spaces.json\n' > "$FX/e2e/.run-outputs"
printf '.pandacorp/run/\ne2e/fixtures/root/ledger.json\ne2e/fixtures/root/ledger.json.lock/\ne2e/fixtures/root/Library/\ne2e/fixtures/root/unlisted\ne2e/fixtures/root/output with spaces.json\n' > "$FX/.gitignore"
cat > "$FX/bin/pnpm" <<'PNPM'
#!/bin/bash
if [ "$1" = vitest ]; then
  printf 'generated by gate\n' > e2e/fixtures/root/ledger.json
  mkdir -p e2e/fixtures/root/generated-empty/.pandacorp/inbox
fi
exit 0
PNPM
chmod +x "$FX/bin/pnpm"
printf '{}\n' > "$FX/package.json"
: > "$FX/playwright.config.ts"
for spec in smoke visual responsive shell headers; do : > "$FX/e2e/$spec.spec.ts"; done
printf 'input\n' > "$FX/e2e/fixtures/root/committed"
git -C "$FX" init -q
git -C "$FX" add .
git -C "$FX" -c user.name=Fixture -c user.email=fixture@example.test commit -qm fixture
cd "$FX"
export PANDACORP_HOST_DIR="$FX/.pandacorp/run/host"
token=$(bash .pandacorp/green-stamp.sh start)
mkdir -p e2e/fixtures/root/ledger.json.lock e2e/fixtures/root/Library/Preferences e2e/fixtures/root/empty/.pandacorp/inbox
printf 'generated\n' > 'e2e/fixtures/root/output with spaces.json'
printf 'generated\n' > e2e/fixtures/root/ledger.json
printf '{}\n' > e2e/fixtures/root/ledger.json.lock/owner.json
printf '{}\n' > e2e/fixtures/root/Library/Preferences/config.json
[ "$(bash .pandacorp/green-stamp.sh start)" = "$token" ]
bash .pandacorp/green-stamp.sh record "$token" >/dev/null
bash .pandacorp/green-stamp.sh check >/dev/null
PATH="$FX/bin:$PATH" bash .pandacorp/verify.sh --light > .pandacorp/run/verify.log 2>&1
for name in ledger.json ledger.json.lock Library empty "output with spaces.json"; do [ ! -e "e2e/fixtures/root/$name" ]; done
# A real full verify can certify despite declared writes and empty directories during its gate.
PATH="$FX/bin:$PATH" bash .pandacorp/verify.sh > .pandacorp/run/verify.log 2>&1
PATH="$FX/bin:$PATH" bash .pandacorp/green-stamp.sh check >/dev/null
# Unlisted ignored output is still a physical input, independently of Git's clean status.
printf 'unexpected\n' > e2e/fixtures/root/unlisted
if bash .pandacorp/green-stamp.sh check --explain 2> .pandacorp/run/err; then echo 'FAIL unlisted ignored output'; exit 1; fi
grep -q 'e2e group' .pandacorp/run/err
rm e2e/fixtures/root/unlisted
for invalid in '../outside' '/tmp/outside' 'e2e/../outside' 'e2e/bad*' 'e2e/' 'e2e/fixtures/root/committed'; do
  printf '%s\n' "$invalid" > e2e/.run-outputs
  git add e2e/.run-outputs
  git -c user.name=Fixture -c user.email=fixture@example.test commit -qm invalid
  if bash .pandacorp/green-stamp.sh clean-outputs > .pandacorp/run/out 2>&1; then echo "FAIL malformed list: $invalid"; exit 1; fi
  if bash .pandacorp/green-stamp.sh start > .pandacorp/run/out 2>&1; then echo "FAIL malformed list fingerprint: $invalid"; exit 1; fi
  grep -q 'invalid e2e/.run-outputs' .pandacorp/run/out
done
# Uncommitted declarations and symlink traversal also fail before deletion.
printf 'e2e/fixtures/root/ledger.json\n' > e2e/.run-outputs
if bash .pandacorp/green-stamp.sh clean-outputs > .pandacorp/run/out 2>&1; then exit 1; fi
git add e2e/.run-outputs
git -c user.name=Fixture -c user.email=fixture@example.test commit -qm valid
rm e2e/fixtures/root/ledger.json
ln -s "$FX/src" e2e/fixtures/root/ledger.json
if bash .pandacorp/green-stamp.sh clean-outputs > .pandacorp/run/out 2>&1; then exit 1; fi
[ -f e2e/fixtures/root/committed ]
echo 'RESULT: 13 passed, 0 failed'
