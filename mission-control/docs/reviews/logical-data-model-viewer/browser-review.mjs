import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from '@playwright/test';

const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:950}});
page.setDefaultTimeout(15000);
const results=[];
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
for(const surface of ['portfolio','board']){
 await page.goto(surface==='portfolio'?'http://127.0.0.1:3019/portfolio?project=Mission%20Control&tab=architecture':'http://127.0.0.1:3019/board');
 if(surface==='board') await page.getByRole('button',{name:/Mission Control factory dashboard/}).click();
 const viewer=page.getByTestId('data-model-viewer');
 await viewer.waitFor();
 const canvas=viewer.getByRole('application');
 assert.equal(await viewer.getByRole('tab',{name:'Diagrama',exact:true}).getAttribute('aria-selected'),'true');
 assert.equal(await viewer.getByRole('table').count(),6);
 assert.equal(await canvas.evaluate(el=>getComputedStyle(el).overflow),'hidden');
 await canvas.scrollIntoViewIfNeeded();
 const before=await canvas.evaluate(el=>el.firstElementChild.style.transform);
 const rect=await canvas.boundingBox();
 assert(rect);
 await page.mouse.move(rect.x+12,rect.y+12);
 await page.mouse.down();
 await page.mouse.move(rect.x+87,rect.y+54,{steps:8});
 await page.mouse.up();
 const after=await canvas.evaluate(el=>el.firstElementChild.style.transform);
 assert.notEqual(after,before);
 await viewer.getByRole('button',{name:'Ver relación users ↔ profiles · Tiene perfil',exact:true}).click();
 assert((await viewer.getByRole('complementary').innerText()).includes('Cada users se relaciona con cero o uno de profiles.'));
 assert((await viewer.getByRole('complementary').innerText()).includes('Cada profiles se relaciona con exactamente uno de users.'));
 await viewer.getByRole('button',{name:'Ampliar modelo',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Modelo de datos',exact:true});
 await dialog.waitFor({state:'visible'});
 await page.keyboard.press('Escape');
 await dialog.waitFor({state:'detached'});
 assert.equal(await page.getByRole('button',{name:'Ampliar modelo',exact:true}).evaluate(el=>el===document.activeElement),true);
 await viewer.getByRole('tab',{name:'Esquema',exact:true}).click();
 assert.equal(await viewer.getByRole('table').count(),0);
 assert.equal(await viewer.locator('pre').count(),6);
 await page.screenshot({path:`docs/reviews/logical-data-model-viewer/${surface}-schema-desktop.png`,fullPage:true});
 await page.setViewportSize({width:375,height:900});
 await page.reload();
 if(surface==='board') await page.getByRole('button',{name:/Mission Control factory dashboard/}).click();
 await viewer.waitFor();
 assert.equal(await viewer.getByRole('tab',{name:'Diagrama',exact:true}).getAttribute('aria-selected'),'true');
 const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 results.push({surface,drag:{before,after},phone:overflow});
 await page.screenshot({path:`docs/reviews/logical-data-model-viewer/${surface}-phone.png`,fullPage:true});
 await page.setViewportSize({width:1280,height:950});
}
assert.deepEqual(errors,[]);
await writeFile('docs/reviews/logical-data-model-viewer/browser-results.json',JSON.stringify({results,pageErrors:errors},null,2));
console.log(JSON.stringify({results,pageErrors:errors}));
await browser.close();
