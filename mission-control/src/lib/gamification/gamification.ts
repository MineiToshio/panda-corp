/** The guild rank ladder — each rank is a BAND of granular levels (not 1:1). */
export const RANKS: readonly Rank[] = RANK_DEFS.map((d, i) => ({
  title: d.es,
  titleEn: d.en,
  icon: d.icon,
  sprite: RANK_SPRITES[i] ?? "human",
  minLevel: RANK_MIN_LEVEL[i] ?? 1,
  grade: rankGrade(d.es),
}));

/** The rank index whose level-band contains the given granular level (0-based). */
export function rankForLevel(level: number): number {
  let idx = 0;
  for (let i = 0; i < RANKS.length; i++) {
    if (level >= (RANKS[i]?.minLevel ?? 1)) idx = i;
  }
  return idx;
}

/** Maximum weekly streak weeks counted (freeze concept — no unbounded multiplier). */
const MAX_STREAK_WEEKS = 52;

/** XP earned per closed work order. */
const XP_PER_WO = 10;

/** XP earned per completed phase. */
const XP_PER_PHASE = 50;

/** XP earned per release / launch (reaching the launched "release" phase). */
const XP_PER_RELEASE = 200;

/** XP earned per green test run (minor confirmation signal). */
const XP_PER_GREEN_TEST = 1;

/** XP earned per week of weekly streak (capped at MAX_STREAK_WEEKS). */
const XP_PER_STREAK_WEEK = 5;

/**
 * The verifiable outcomes that drive guild XP.
 *
 * Each field maps to a source from the honesty contract (blueprint §2):
 *   - `workOrdersDone`  ← `status.yaml:work_orders_done` / `achievement` event with workOrder
 *   - `phasesCompleted` ← `status.yaml:phase` transitions
 *   - `releases`        ← `phase: release` reached in portfolio
 *   - `greenTestRuns`   ← `test_ok` events
 *   - `weeklyStreak`    ← optional; weekly cadence with freeze (never daily-reset)
 *
 * Deliberately ABSENT from this type (FRD-09 ethical constraint):
 *   - No `appOpens`, `navigations`, `pageViews` — activity is NOT rewarded.
 *   - No `dailyStreak` — only `weeklyStreak` with freeze.
 */
export type GuildOutcomes = {
  /** Number of work orders closed green. */
  readonly workOrdersDone: number;
  /** Number of phases completed (design, architecture, implementation, release). */
  readonly phasesCompleted: number;
  /** Number of releases (projects reaching the launched "release" phase). */
  readonly releases: number;
  /** Number of green test suite runs. */
  readonly greenTestRuns: number;
  /**
   * Current weekly streak (weeks with at least one closed WO).
   * Optional — omit or set to 0 for no streak bonus.
   * Capped at MAX_STREAK_WEEKS (freeze concept).
   */
  readonly weeklyStreak?: number;
};

/**
 * The computed guild level result.
 *
 * All fields are derived purely from GuildOutcomes — no I/O, no clock, no engagement bonus.
 */
export type GuildLevel = {
  /** Granular guild level (1+), derived from XP — climbs faster than the rank. */
  readonly level: number;
  /** Current rank index in RANKS (0-based; a rank spans a band of levels). */
  readonly rankIndex?: number;
  /** Human-readable rank title (Spanish) from the RANKS ladder. */
  readonly title: string;
  /**
   * English rank name + Órbita icon for the current rank. Always set by
   * computeGuildLevel; optional so hand-built test fixtures stay terse.
   */
  readonly titleEn?: string;
  readonly icon?: IconName;
  /** Rank-family sprite slug → /ranks/<slug>.png. */
  readonly sprite?: string;
  /** Current rank's sub-grade: 1/2/3 (I·II·III), 0 = none. */
  readonly grade?: number;
  /** Total accumulated XP (sum of all verifiable outcomes). */
  readonly xp: number;
  /** XP required to reach the NEXT granular level. */
  readonly next: number;
  /**
   * Percentage progress toward the next LEVEL, 0–100.
   * Exactly 0 when xp = 0 (honest zero state — never near 80% with no real work).
   */
  readonly pctToNext: number;
};

/**
 * Compute the guild's current level, title, XP, next threshold and progress bar
 * from a set of verifiable real outcomes (WO-09-001, IF-09-guild-xp).
 *
 * Pure function: no I/O, no clock, no time-decay, no engagement bonus, no mutation.
 * Same outcomes always produce the same result.
 *
 * XP is derived ONLY from the honesty contract (blueprint §2):
 *   work orders done, phases completed, releases, green test runs, weekly streak.
 *
 * Forbidden (never contributes XP):
 *   - App opens, navigation, page views, messages, file reads/writes.
 *   - Daily-reset streaks (only weekly, capped).
 *
 * Honest zero state: when all outcome counts are zero, xp = 0, pctToNext = 0,
 * level = 1, title = RANKS[0].title. The bar is NEVER artificially inflated.
 */
export function computeGuildLevel(outcomes: GuildOutcomes): GuildLevel {
  // ── XP derivation (honesty contract) ──────────────────────────────────────
  const cappedStreak = Math.min(
    Math.max(0, Math.trunc(outcomes.weeklyStreak ?? 0)),
    MAX_STREAK_WEEKS,
  );

  const xp =
    outcomes.workOrdersDone * XP_PER_WO +
    outcomes.phasesCompleted * XP_PER_PHASE +
    outcomes.releases * XP_PER_RELEASE +
    outcomes.greenTestRuns * XP_PER_GREEN_TEST +
    cappedStreak * XP_PER_STREAK_WEEK;

  // ── Granular level + rank band ──────────────────────────────────────────────
  // The level climbs with XP; the rank is the BAND the level falls into (the last
  // rank whose minLevel ≤ level). Level ≠ rank (a rank spans several levels).
  const level = levelForXp(xp);
  const rankIndex = rankForLevel(level);
  // biome-ignore lint/style/noNonNullAssertion: RANKS is non-empty (40 ranks, verified by tests)
  const currentRank = RANKS[rankIndex]!;

  // ── Progress to the NEXT granular level (the hero/header bar) ────────────────
  const curLevelXp = xpForLevel(level);
  const nextLevelXp = xpForLevel(level + 1);
  const span = nextLevelXp - curLevelXp;
  const pctToNext =
    span > 0 ? Math.min(100, Math.max(0, Math.floor(((xp - curLevelXp) / span) * 100))) : 0;

  return {
    level,
    rankIndex,
    title: currentRank.title,
    titleEn: currentRank.titleEn,
    icon: currentRank.icon,
    sprite: currentRank.sprite,
    grade: currentRank.grade,
    xp,
    next: nextLevelXp,
    pctToNext,
  };
}

// ---------------------------------------------------------------------------
// deriveGuildOutcomes — aggregate real outcomes from portfolio statuses + events (WO-09-004)
//
// Pure derivation layer: takes already-read data and produces GuildOutcomes.
// No I/O — the caller (Server Component in app/layout.tsx) reads the data;
// this function only processes what it receives (architecture §6: data layer
// boundary is lib/, components never touch fs directly).
// ---------------------------------------------------------------------------

/**
 * Input for deriveGuildOutcomes: the already-read statuses for every portfolio project
 * and the events snapshot (for green test runs).
 */
export type GuildOutcomesInput = {
  /** StatusResult for each portfolio project (read via readStatus) — used for phase/release only. */
  statuses: readonly StatusResult[];
  /**
   * Events snapshot from readEvents() (for greenTestRuns count).
   * May be omitted (treated as zero test runs).
   */
  eventsSnapshot?: EventsSnapshot | null;
  /**
   * Current weekly streak (weeks with at least one closed WO).
   * Optional — 0 when not tracked yet.
   */
  weeklyStreak?: number;
  /**
   * LIVE total of work orders in state "done", summed across the whole portfolio
   * (DR-092/DR-115: derived by the caller from `listWorkOrders(path).filter(state === "done")`,
   * never from the stale `status.yaml:work_orders_done` cache). Omitted/non-finite → 0
   * (honest zero, same guard as the removed per-status tally).
   */
  workOrdersDoneLive?: number;
};

/**
 * Derive GuildOutcomes from the portfolio's real data (WO-09-004, AC-09-004.1).
 *
 * Honesty contract (blueprint §2):
 *   - workOrdersDone  = workOrdersDoneLive, the LIVE count of WOs in state "done" across the
 *                       portfolio (caller-derived from listWorkOrders — DR-092/DR-115); the
 *                       cached status.yaml work_orders_done counter is never read here
 *   - phasesCompleted = count of projects whose phase is in { design, architecture, implementation,
 *                       release } (each project that advanced past product = 1 phase)
 *   - releases        = count of projects in the launched "release" phase (reached launch)
 *   - greenTestRuns   = count of "test_ok" events in the snapshot
 *
 * All missing/malformed statuses are skipped (never throws, fail-soft).
 * Never inflates XP — strictly derived from verifiable outcomes.
 *
 * Pure function: no I/O, no side-effects, same input → same output.
 */
export function deriveGuildOutcomes(input: GuildOutcomesInput): GuildOutcomes {
  const { statuses, eventsSnapshot, weeklyStreak, workOrdersDoneLive } = input;

  let phasesCompleted = 0;
  let releases = 0;

  for (const sr of statuses) {
    const tally = _tallyStatus(sr);
    phasesCompleted += tally.phasesCompleted;
    releases += tally.releases;
  }

  // workOrdersDone: LIVE count supplied by the caller (readGuildState sums
  // listWorkOrders(project).filter(state === "done") across the portfolio — DR-115),
  // never the stale status.yaml cache. Same guard shape as the old per-status tally
  // (finite, non-negative, truncated) so a malformed caller input can't poison XP.
  const workOrdersDone =
    typeof workOrdersDoneLive === "number" && Number.isFinite(workOrdersDoneLive)
      ? Math.max(0, Math.trunc(workOrdersDoneLive))
      : 0;

  return {
    workOrdersDone,
    phasesCompleted,
    releases,
    greenTestRuns: _countGreenTestRuns(eventsSnapshot),
    weeklyStreak: weeklyStreak ?? 0,
  };
}

/** Phases that count as advanced past "product" (one phaseCompleted each). */
const COMPLETED_PHASES = new Set(["design", "architecture", "implementation", "release"]);

/**
 * Per-project phase/release contribution to the guild outcomes (workOrdersDone is no
 * longer tallied per-status — see deriveGuildOutcomes). Behavior copied verbatim from
 * the original inline loop body (fail-soft: absent/null status → all zeros).
 */
function _tallyStatus(sr: StatusResult): {
  phasesCompleted: number;
  releases: number;
} {
  if (!sr.present || sr.status === null) {
    return { phasesCompleted: 0, releases: 0 };
  }
  const st = sr.status;

  // phasesCompleted: project advanced beyond "product" phase
  const phasesCompleted = typeof st.phase === "string" && COMPLETED_PHASES.has(st.phase) ? 1 : 0;

  // releases: project reached the launched "release" phase (DR-085)
  const releases = st.phase === "release" ? 1 : 0;

  return { phasesCompleted, releases };
}

/** Count "test_ok" events in the snapshot (0 when absent). Behavior copied verbatim. */
function _countGreenTestRuns(eventsSnapshot: EventsSnapshot | null | undefined): number {
  if (!eventsSnapshot) return 0;
  let greenTestRuns = 0;
  for (const ev of semanticLedger(eventsSnapshot.events)) {
    if (ev.event === "test_ok") {
      greenTestRuns += 1;
    }
  }
  return greenTestRuns;
}
